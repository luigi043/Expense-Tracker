package com.expensetracker

import android.graphics.Bitmap
import android.os.Build
import androidx.compose.ui.test.*
import androidx.compose.ui.test.junit4.createAndroidComposeRule
import androidx.test.platform.app.InstrumentationRegistry
import java.io.File
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test

/** Run only on the explicitly selected synthetic-data emulator, never a user's phone. */
class NativeWalkthroughTest {
    @get:Rule val compose = createAndroidComposeRule<MainActivity>()

    private fun shot(name: String) {
        compose.waitForIdle()
        Thread.sleep(700)
        val instrumentation = InstrumentationRegistry.getInstrumentation()
        val directory = File(instrumentation.targetContext.getExternalFilesDir(null), "verification")
        directory.mkdirs()
        val bitmap = instrumentation.uiAutomation.takeScreenshot()
        File(directory, "$name.png").outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
        bitmap.recycle()
    }

    private fun waitText(value: String) { compose.waitUntil(15_000) { compose.onAllNodesWithText(value, useUnmergedTree = true).fetchSemanticsNodes().isNotEmpty() } }
    private fun text(value: String) = compose.onNodeWithText(value, useUnmergedTree = true)
    private fun button(value: String) = compose.onNode(hasClickAction() and (hasText(value) or hasAnyDescendant(hasText(value))), useUnmergedTree = true)
    private fun field(label: String) = compose.onNode(hasSetTextAction() and (hasText(label) or hasAnyDescendant(hasText(label))), useUnmergedTree = true)
    private fun back() { androidx.test.espresso.Espresso.closeSoftKeyboard(); androidx.test.espresso.Espresso.pressBack(); compose.waitForIdle() }
    private fun navigate(label: String) = compose.onNodeWithContentDescription(label, useUnmergedTree = true).performClick()

    @Test fun walkThroughEveryNativeScreenUsingSyntheticTransactions() {
        assertTrue("Emulator required", Build.MODEL.contains("sdk", true) || Build.FINGERPRINT.contains("emulator", true))
        compose.waitForIdle()
        shot("00-initial-state")
        android.util.Log.i("TrackerWalkthrough", compose.onRoot().printToString())
        compose.waitUntil(30_000) { compose.onAllNodesWithText("Add Transaction", useUnmergedTree = true).fetchSemanticsNodes().isNotEmpty() }
        shot("01-dashboard-empty")
        navigate("History")
        waitText("No transactions found")
        text("No transactions found").assertExists()
        shot("02-history-empty")
        navigate("Budget")
        shot("03-budget-empty")
        compose.onAllNodesWithContentDescription("Add budget", useUnmergedTree = true)[0].performClick()
        shot("04-budget-dialog")
        text("Save").performClick()
        text("Enter a valid amount").assertExists()
        shot("05-budget-validation")
        field("Monthly Limit (USD)").performTextInput("300")
        text("Save").performClick()
        shot("06-budget-saved")
        navigate("Home")
        text("Add Transaction").performClick()
        shot("07-add-transaction")
        button("Add Transaction").performScrollTo().performClick()
        text("Please enter a valid positive amount").assertExists()
        field("Amount").performScrollTo()
        shot("08-transaction-validation")
        field("Amount").performTextInput("42.50")
        field("Note (optional)").performTextInput("Synthetic client lunch")
        navigate("Pick date")
        shot("09-date-picker")
        text("Cancel").performClick()
        navigate("Change currency")
        shot("10-transaction-currency-picker")
        compose.onNode(hasText("USD") and hasAnyAncestor(isDialog()), useUnmergedTree = true).performClick()
        button("Add Transaction").performScrollTo().performClick()
        compose.waitUntil(15_000) { compose.onAllNodesWithText("Spending by Category", useUnmergedTree = true).fetchSemanticsNodes().isNotEmpty() }
        shot("11-dashboard-populated")
        navigate("History")
        text("Synthetic client lunch").assertExists()
        shot("12-history-populated")
        navigate("Filter")
        shot("13-history-filters")
        text("From date").performClick()
        shot("26-history-from-date")
        text("Cancel").performClick()
        text("To date").performClick()
        shot("27-history-to-date")
        text("Cancel").performClick()
        navigate("Filter")
        text("Synthetic client lunch").performClick()
        shot("14-edit-transaction")
        field("Amount").performTextReplacement("45")
        text("Save Changes").performScrollTo().performClick()
        text("Synthetic client lunch").performClick()
        navigate("Delete")
        shot("15-delete-confirmation")
        text("Cancel").performClick()
        back()
        navigate("Export")
        shot("16-export-menu")
        back()
        navigate("Settings")
        shot("17-settings")
        text("Change").performClick()
        shot("18-base-currency-picker")
        back()
        navigate("Open currency converter")
        shot("19-currency-converter")
        field("Amount").performTextReplacement("-2")
        text("Enter a valid non-negative amount").assertExists()
        shot("20-converter-validation")
        field("Amount").performTextReplacement("12")
        text("To").performClick()
        shot("28-converter-currency-picker")
        compose.onNode(hasText("USD") and hasAnyAncestor(isDialog()), useUnmergedTree = true).performClick()
        text("$ 12.00").assertExists()
        shot("29-converter-offline-result")
        text("To").performClick()
        compose.onNode(hasText("EUR") and hasAnyAncestor(isDialog()), useUnmergedTree = true).performClick()
        text("Currency conversion needs an exchange-rate API key. Same-currency calculations work offline.").assertExists()
        shot("30-converter-unconfigured")
        back()
        navigate("Open recurring expenses")
        shot("21-recurring-empty")
        navigate("Add recurring")
        shot("22-recurring-dialog")
        text("Save").performClick()
        text("Enter a valid positive amount").assertExists()
        shot("23-recurring-validation")
        field("Amount").performTextInput("25")
        field("Note (optional)").performTextInput("Synthetic subscription")
        text("Save").performClick()
        waitText("Housing")
        text("Housing").assertExists()
        shot("24-recurring-saved")
        compose.onAllNodes(isToggleable(), useUnmergedTree = true)[0].performClick()
        shot("31-recurring-paused")
        navigate("Delete recurring entry")
        shot("32-recurring-delete-confirmation")
        text("Cancel").performClick()
        back()
        navigate("Budget")
        waitText("Spent: $ 45.00")
        text("Spent: $ 45.00").assertExists()
        shot("25-budget-spending")
        navigate("Settings")
        compose.onAllNodes(isToggleable(), useUnmergedTree = true)[0].performClick()
        waitText("Dark theme active")
        compose.activityRule.scenario.onActivity {
            org.junit.Assert.assertFalse(androidx.core.view.WindowCompat.getInsetsController(it.window, it.window.decorView).isAppearanceLightStatusBars)
        }
        shot("33-settings-dark")
        compose.onAllNodes(isToggleable(), useUnmergedTree = true)[0].performClick()
        compose.activityRule.scenario.recreate()
        navigate("History")
        text("Synthetic client lunch").assertExists()
        shot("34-history-after-recreation")
        text("Synthetic client lunch").performClick()
        navigate("Delete")
        text("Delete").performClick()
        waitText("No transactions found")
        text("No transactions found").assertExists()
        shot("35-transaction-deleted")
        navigate("Home")
        text("Add Transaction").performClick()
        text("💰 Income").performClick()
        field("Amount").performTextInput("1000")
        field("Note (optional)").performTextInput("Synthetic salary")
        shot("36-income-form")
        button("Add Transaction").performScrollTo().performClick()
        compose.waitUntil(15_000) { compose.onAllNodesWithText("$ 1000.00", useUnmergedTree = true).fetchSemanticsNodes().isNotEmpty() }
        shot("37-income-dashboard")
    }
}
